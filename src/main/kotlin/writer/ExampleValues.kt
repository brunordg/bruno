package com.codeteam.writer

import com.codeteam.model.ValidationConstraints
import java.text.Normalizer

/**
 * Picks the example value for a field or parameter from its name, Java type and
 * validation constraints. Names are matched by whole words (English or Portuguese),
 * never by substrings, so `paid` is not an id and `cancelReason` is not a phone.
 */
internal object ExampleValues {

    /** Runtime variables set by [DATE_SCRIPT]; plain names, not Bruno's `$` built-ins. */
    const val RANDOM_DATE = "{{randomDate}}"
    const val RANDOM_PAST_DATE = "{{randomPastDate}}"
    const val RANDOM_FUTURE_DATE = "{{randomFutureDate}}"
    const val RANDOM_DATE_TIME = "{{randomDateTime}}"
    const val RANDOM_TIME = "{{randomTime}}"

    /** Collection-level pre-request script that fills the date variables in java.time formats. */
    val DATE_SCRIPT = """
        script:pre-request {
          // Generated by Bruno Generator: dates in java.time formats
          const pad = (n) => String(n).padStart(2, "0");
          const day = (offset) => new Date(Date.now() + offset * 86400000);
          const rnd = (min, max) => min + Math.floor(Math.random() * (max - min + 1));
          const date = (d) => d.getFullYear() + "-" + pad(d.getMonth() + 1) + "-" + pad(d.getDate());
          const time = (d) => pad(d.getHours()) + ":" + pad(d.getMinutes()) + ":" + pad(d.getSeconds());
          bru.setVar("randomDate", date(day(rnd(-365, 365))));
          bru.setVar("randomPastDate", date(day(-rnd(1, 3650))));
          bru.setVar("randomFutureDate", date(day(rnd(1, 365))));
          bru.setVar("randomDateTime", date(day(rnd(-365, 365))) + "T" + time(new Date()));
          bru.setVar("randomTime", time(new Date()));
          // Start/end pairs share one day, so the start is never after the end
          const span = date(day(rnd(-365, 365)));
          bru.setVar("randomStartDate", span);
          bru.setVar("randomEndDate", span);
          bru.setVar("randomStartDateTime", span + "T00:00:00");
          bru.setVar("randomEndDateTime", span + "T23:59:59");
          bru.setVar("randomStartTime", "00:00:00");
          bru.setVar("randomEndTime", "23:59:59");
          bru.setVar("randomStartTimestamp", span + "T00:00:00Z");
          bru.setVar("randomEndTimestamp", span + "T23:59:59Z");
        }
    """.trimIndent() + "\n"

    private val PAST_WORDS = setOf("birth", "birthday", "nascimento", "created", "criado")
    private val FUTURE_WORDS = setOf("expiration", "expires", "due", "vencimento", "validade")
    private val START_WORDS = setOf("start", "starts", "begin", "begins", "from", "inicio")
    private val END_WORDS = setOf("end", "ends", "finish", "until", "fim", "termino")
    private val PAGE_NAMES = setOf("page", "pagina")
    private val SIZE_NAMES = setOf("size", "limit", "pagesize", "tamanho", "limite")
    private const val SHORT_STRING_MAX = 10

    private class Rule(val wordSets: List<Set<String>>, val value: (TypeInfo) -> String)

    private fun rule(vararg sets: String, value: (TypeInfo) -> String) =
        Rule(sets.map { it.split(' ').toSet() }, value)

    private fun rule(vararg sets: String, value: String) = rule(*sets) { value }

    // Order breaks ties between rules matching the same number of words.
    private val RULES: List<Rule> = listOf(
        rule("first name", "primeiro nome", value = "{{\$randomFirstName}}"),
        rule("last name", "sobrenome", "ultimo nome", value = "{{\$randomLastName}}"),
        rule("full name", "nome completo", value = "{{\$randomFullName}}"),
        rule("username", "user name", "login", "usuario", "nome usuario", value = "{{\$randomUserName}}"),
        rule("email", "mail", value = "{{\$randomEmail}}"),
        rule("password", "pwd", "senha", value = "{{\$randomPassword}}"),
        rule("phone", "mobile", "telefone", "celular", "fone", value = "{{\$randomPhoneNumber}}"),
        rule("street", "address", "rua", "logradouro", "endereco", value = "{{\$randomStreetAddress}}"),
        rule("city", "cidade", "municipio", value = "{{\$randomCity}}"),
        rule("country code", "codigo pais", value = "{{\$randomCountryCode}}"),
        rule("country", "pais", value = "{{\$randomCountry}}"),
        rule("company", "empresa", "razao social", value = "{{\$randomCompanyName}}"),
        rule("job title", "job", "occupation", "cargo", "profissao", value = "{{\$randomJobTitle}}"),
        rule("url", "website", "site", "link", value = "{{\$randomUrl}}"),
        rule("avatar", "photo", "image", "foto", "imagem", value = "{{\$randomAvatarImage}}"),
        rule("ip", value = "{{\$randomIP}}"),
        rule("latitude", "lat", value = "{{\$randomLatitude}}"),
        rule("longitude", "lng", "lon", value = "{{\$randomLongitude}}"),
        rule("currency", "moeda", value = "{{\$randomCurrencyCode}}"),
        rule("color", "cor", value = "{{\$randomHexColor}}"),
        rule("file name", "nome arquivo", value = "{{\$randomFileName}}"),
        rule("mime type", "content type", value = "{{\$randomMimeType}}"),
        rule("locale", "language", "idioma", value = "{{\$randomLocale}}"),
        rule("slug", value = "{{\$randomLoremSlug}}"),
        rule("version", "versao", value = "{{\$randomSemver}}"),
        rule(
            "description", "comment", "notes", "descricao", "observacao", "comentario",
            value = "{{\$randomLoremSentence}}"
        ),
        rule("zip", "postal", "cep", value = "{{\$randomInt}}"),
        rule("price", "amount", "total", "preco", "valor") { type ->
            if (type.isInteger) "{{\$randomInt}}" else "{{\$randomPrice}}"
        }
    )

    private val FULL_NAME_ALONE = setOf(listOf("name"), listOf("nome"))

    fun tokenize(name: String): List<String> {
        val ascii = Normalizer.normalize(name, Normalizer.Form.NFD).replace(Regex("\\p{M}+"), "")
        return ascii
            .replace(Regex("([a-z0-9])([A-Z])"), "$1 $2")
            .replace(Regex("([A-Z]+)([A-Z][a-z])"), "$1 $2")
            .replace(Regex("([A-Za-z])([0-9])"), "$1 $2")
            .replace(Regex("([0-9])([A-Za-z])"), "$1 $2")
            .split(Regex("[^A-Za-z0-9]+"))
            .filter { it.isNotEmpty() }
            .map { it.lowercase() }
    }

    fun valueFor(name: String, type: String, constraints: ValidationConstraints = ValidationConstraints()): String {
        val words = tokenize(name)
        val info = TypeInfo.of(type)

        pagination(words, info)?.let { return it }
        dateValue(words, info, constraints)?.let { return it }

        val value = when {
            words.lastOrNull() == "id" -> if (info.isNumeric) "{{\$randomInt}}" else "{{\$randomUUID}}"
            else -> dictionary(words, info) ?: byType(info) ?: fallback(name, info)
        }
        return refine(value, info, constraints)
    }

    private fun pagination(words: List<String>, info: TypeInfo): String? {
        if (!info.isNumeric) return null
        val joined = words.joinToString("")
        return when {
            joined in PAGE_NAMES -> "0"
            joined in SIZE_NAMES -> "20"
            else -> null
        }
    }

    private fun dateValue(words: List<String>, info: TypeInfo, constraints: ValidationConstraints): String? {
        val kind = DATE_KINDS[info.simple] ?: return null
        if (kind == "Date") {
            if (constraints.past) return RANDOM_PAST_DATE
            if (constraints.future) return RANDOM_FUTURE_DATE
        }
        when {
            words.any { it in START_WORDS } -> return "{{randomStart$kind}}"
            words.any { it in END_WORDS } -> return "{{randomEnd$kind}}"
        }
        return when (kind) {
            "Date" -> when {
                words.any { it in PAST_WORDS } -> RANDOM_PAST_DATE
                words.any { it in FUTURE_WORDS } -> RANDOM_FUTURE_DATE
                else -> RANDOM_DATE
            }
            "DateTime" -> RANDOM_DATE_TIME
            "Time" -> RANDOM_TIME
            else -> "{{\$isoTimestamp}}"
        }
    }

    // Java type -> suffix of the script's start/end variables.
    private val DATE_KINDS = mapOf(
        "localdate" to "Date",
        "localdatetime" to "DateTime",
        "localtime" to "Time",
        "instant" to "Timestamp",
        "offsetdatetime" to "Timestamp",
        "zoneddatetime" to "Timestamp",
        "date" to "Timestamp",
        "timestamp" to "Timestamp"
    )

    private fun dictionary(words: List<String>, info: TypeInfo): String? {
        if (words in FULL_NAME_ALONE) return "{{\$randomFullName}}"
        val present = words.toSet()
        var best: Rule? = null
        var bestScore = 0
        for (rule in RULES) {
            val score = rule.wordSets.filter { present.containsAll(it) }.maxOfOrNull { it.size } ?: 0
            if (score > bestScore) {
                best = rule
                bestScore = score
            }
        }
        return best?.value?.invoke(info)
    }

    private fun byType(info: TypeInfo): String? = when (info.simple) {
        "boolean" -> "{{\$randomBoolean}}"
        "uuid" -> "{{\$randomUUID}}"
        else -> null
    }

    private fun fallback(name: String, info: TypeInfo): String = when {
        info.isString -> "{{\$randomLoremWord}}"
        info.isDecimal -> "{{\$randomPrice}}"
        info.isNumeric -> "{{\$randomInt}}"
        else -> "{{$name}}"
    }

    private fun refine(value: String, info: TypeInfo, constraints: ValidationConstraints): String {
        val maxSize = constraints.maxSize
        return when {
            constraints.positive && constraints.min == null && value == "{{\$randomInt}}" -> "1"
            maxSize != null && maxSize <= SHORT_STRING_MAX && value == "{{\$randomLoremSentence}}" ->
                "{{\$randomLoremWord}}"
            else -> value
        }
    }

    private class TypeInfo(val simple: String) {
        val isString get() = simple == "string" || simple == "charsequence"
        val isDecimal get() = simple in DECIMAL_TYPES
        val isInteger get() = simple in INTEGER_TYPES
        val isNumeric get() = isDecimal || isInteger || simple == "number"

        companion object {
            private val INTEGER_TYPES = setOf("int", "integer", "long", "short", "byte", "biginteger")
            private val DECIMAL_TYPES = setOf("double", "float", "bigdecimal")

            /** `java.time.LocalDate` / `Optional<Long>` / `Boolean` -> `localdate` / `optional` / `boolean`. */
            fun of(type: String): TypeInfo =
                TypeInfo(type.substringBefore('<').substringAfterLast('.').trim().lowercase())
        }
    }
}
